/**
 * 视网膜“懒重采样 / 预测编码”实验骨架（三触发源 + 粒子兴奋点通道）。
 *
 * <p>目标：缓解“每 tick 全量重扫 ~11000 方块做查询/标签/toString()”这一 CPU 热点。
 * 判断标准：<b>“为了知道哪里该省而必须先做的动作，必须比被省掉的动作更便宜”</b>。
 * 即“哪里变了/哪里显著”必须来自免费或廉价的侧信道（方块事件、自身状态、实体/粒子事件），
 * 而不是“自己先全图扫描去找差异”——后者等于没省。</p>
 *
 * <p>分级响应（决定性设计）：</p>
 * <table border="1">
 *   <tr><th>观察者</th><th>世界</th><th>处理</th><th>成本</th></tr>
 *   <tr><td>静止</td><td>方块未变</td><td>沿用缓存</td><td>真省</td></tr>
 *   <tr><td>静止</td><td>方块变了</td><td>事件驱动重扫那一格</td><td>真省</td></tr>
 *   <tr><td>移动（位置变）</td><td>任意</td><td>增量重扫（只扫新露出的边缘格）</td><td>真省</td></tr>
 *   <tr><td>转头（yaw/pitch 变）</td><td>任意</td><td>全量重扫（视锥旋转，新旧视野几乎不重叠）</td><td>省不了，但必要</td></tr>
 *   <tr><td>任意</td><td>实体游走</td><td>常驻高频更新实体所在格（实体少，不懒）</td><td>便宜</td></tr>
 *   <tr><td>任意</td><td>粒子/药水效果</td><td>激活兴奋点，不打标签缓存（见 {@link #handleParticleEvents}）</td><td>恒定、不逐粒采样</td></tr>
 * </table>
 *
 * <p>要点：自运动检测极便宜（bot 自身的 position/yaw/pitch 每 tick 都在，几个浮点比较），
 * 是免费侧信道；贵的是“变了之后的重扫”。转头必须全量（不能省，否则撞墙；人脑扫视也是
 * 全量采新注视点，扫视抑制抑制的是识别而非采样）。移动增量才是懒采样真正赚的地方。
 * 实体少 → 不懒、常驻高频；粒子短命且信息多在 client 侧 → 不做逐粒采样，只打兴奋点。</p>
 */
